#!/usr/bin/env bash
export LC_ALL=C.UTF-8
# Caelestia Shortcuts Cheatsheet (100% Pure Caelestia + Neovim)

SHORTCUTS=(
    "─── FONDS D'ÉCRAN & THÈMES ────────────────────────────────"
    "SUPER + SHIFT + W             │ Galerie visuelle des fonds d'écran (avec aperçus)"
    "SUPER + ALT + W               │ Fond d'écran aléatoire instantané"
    ""
    "─── APPLICATIONS ──────────────────────────────────────────"
    "SUPER + T                     │ Terminal Foot (Caelestia natif)"
    "SUPER + W                     │ Navigateur Web Helium Browser"
    "SUPER + C                     │ Éditeur Neovim (dans Foot)"
    "SUPER + E                     │ Gestionnaire de fichiers Thunar"
    "CTRL + ALT + V                │ Mixeur audio pwvucontrol"
    ""
    "─── CAELESTIA SHELL (QUICKSHELL) ──────────────────────────"
    "SUPER (Tap)                   │ Lanceur d'applications Quickshell"
    "SUPER + N                     │ Tiroir latéral (Contrôles & Notifications)"
    "SUPER + L                     │ Verrouiller l'écran (Lockscreen Quickshell)"
    "CTRL + ALT + SUPPR            │ Menu de session (Éteindre / Reboot / Veille)"
    "SUPER + K                     │ Afficher tous les panneaux Quickshell"
    "CTRL + ALT + C                │ Effacer les notifications"
    "CTRL + SUPER + ALT + R        │ Redémarrer Caelestia Shell"
    ""
    "─── NAVIGATION WORKSPACES (BUREAUX) ───────────────────────"
    "SUPER + &  é  \"  '  (  -  è  _  ç  à │ Aller au bureau 1 à 10 (Touches physiques 1..0)"
    "SUPER + SHIFT + 1 .. 10      │ Déplacer la fenêtre vers le bureau 1 à 10"
    "CTRL + SUPER + Flèche Droite │ Bureau suivant (+1)"
    "CTRL + SUPER + Flèche Gauche │ Bureau précédent (-1)"
    "SUPER + Molette Souris        │ Faire défiler les bureaux"
    ""
    "─── WORKSPACES SPÉCIAUX ───────────────────────────────────"
    "SUPER + S                     │ Espace spécial scratchpad"
    "SUPER + M                     │ Espace Musique (Spotify)"
    "SUPER + D                     │ Espace Communication (Discord / WhatsApp)"
    "CTRL + SHIFT + ECHAP          │ Espace Moniteur Système (Btop)"
    "SUPER + R                     │ Espace Tâches (Todoist)"
    ""
    "─── GESTION DES FENÊTRES ──────────────────────────────────"
    "SUPER + Q                     │ Fermer la fenêtre active"
    "SUPER + ALT + ESPACE          │ Basculer fenêtre flottante"
    "SUPER + F                     │ Plein écran classique (Fullscreen)"
    "SUPER + ALT + F               │ Mode Zoom Niri (Plein écran + Navigation 2D)"
    "SUPER + P                     │ Épingler la fenêtre"
    "SUPER + Flèches               │ Focus 2D (normal ou slide Niri si zoomé)"
    "SUPER + SHIFT + Flèches       │ Déplacer la fenêtre"
    "SUPER + Clic Gauche (Glisser) │ Déplacer à la souris"
    "SUPER + Clic Droit (Glisser)  │ Redimensionner à la souris"
    "CTRL + SUPER + \\              │ Centrer la fenêtre"
    ""
    "─── PRESSE-PAPIER & CAPTURES ──────────────────────────────"
    "SUPER + V                     │ Historique du presse-papier (Fuzzel)"
    "SUPER + .                     │ Sélecteur d'émojis"
    "IMPR ÉCRAN                    │ Capture d'écran (Swappy)"
    "SUPER + SHIFT + S             │ Capture d'écran zone gelée"
    "CTRL + ALT + R                │ Enregistrement vidéo d'écran"
    "SUPER + SHIFT + C             │ Pipette à couleurs (Color Picker)"
    ""
    "─── AUDIO & MICROPHONE ────────────────────────────────────"
    "SUPER + ALT + M               │ Couper / Réactiver le microphone (Mute toggle)"
    "SUPER + SHIFT + M             │ Couper / Réactiver la sortie son (Speakers)"
    ""
    "─── AIDE ──────────────────────────────────────────────────"
    "SUPER + /  ou  SUPER + H      │ Afficher cette aide des raccourcis"
)

if command -v fuzzel >/dev/null 2>&1; then
    printf '%s\n' "${SHORTCUTS[@]}" | fuzzel -d -p "Raccourcis Caelestia > " --width 65 --lines 20
elif command -v rofi >/dev/null 2>&1; then
    printf '%s\n' "${SHORTCUTS[@]}" | rofi -dmenu -i -p "󰌌 Raccourcis Caelestia"
fi
